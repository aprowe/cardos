#!/usr/bin/env python3
"""Make apps/wordle/wordle_words.h, Wordle's word list, from apps/wordle/tools/wordle/.

    python apps/wordle/tools/make_wordle.py

Sources, all in apps/wordle/tools/wordle/:
  enable5.txt   ENABLE2K's five-letter words (public domain): what a guess
                may be
  blocked.txt   words of that list Wordle will not accept
  answers.txt   the words a puzzle can be, written for CardOS by hand; every
                one must be an accepted word

One list, packed. A word's first two letters pick a bucket (26 x 26) and
the other three are 15 bits of a uint16_t; the top bit says the word is also
an answer. WD_BUCKET[b] is where bucket b starts in WD_TAIL, sorted, so a
lookup is a binary search of a dozen entries. Two bytes a word: the whole
thing is constants, in flash, but the launcher's icon scan reads an app's
constants into RAM, so it is kept small (about 18 KB for ~8,600 words).

The daily puzzle walks the answers in a scrambled order that repeats only
after all of them: answer (day * WD_DAILY_MUL + WD_DAILY_ADD) % WD_NANSWERS,
with WD_DAILY_MUL coprime with the count, chosen here.
"""

import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
SRC = os.path.join(ROOT, "apps", "wordle", "tools", "wordle")
OUT = os.path.join(ROOT, "apps", "wordle", "wordle_words.h")


def words(name):
    out = []
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        for line in f:
            if line.lstrip().startswith("#"):
                continue
            out += line.split()
    for w in out:
        if len(w) != 5 or not w.isalpha() or not w.islower() or not w.isascii():
            raise SystemExit("%s: '%s' is not five lowercase letters" % (name, w))
    return out


def main():
    accepted = set(words("enable5.txt"))
    blocked = set(words("blocked.txt"))
    answers = words("answers.txt")
    if len(set(answers)) != len(answers):
        dup = sorted(w for w in set(answers) if answers.count(w) > 1)
        raise SystemExit("answers.txt: twice: %s" % " ".join(dup))
    missing = [w for w in answers if w not in accepted]
    if missing:
        raise SystemExit("answers.txt: not in enable5.txt: %s" % " ".join(missing))
    bad = [w for w in answers if w in blocked]
    if bad:
        raise SystemExit("answers.txt: blocked: %s" % " ".join(bad))
    accepted -= blocked
    answer_set = set(answers)
    allw = sorted(accepted)
    if len(allw) >= 65536:
        raise SystemExit("too many words for uint16_t offsets")

    def val(c):
        return ord(c) - ord("a")

    buckets = [0] * (26 * 26 + 1)
    tails = []
    for w in allw:
        buckets[val(w[0]) * 26 + val(w[1]) + 1] += 1
        t = (val(w[2]) << 10) | (val(w[3]) << 5) | val(w[4])
        if w in answer_set:
            t |= 0x8000
        tails.append(t)
    for i in range(1, len(buckets)):
        buckets[i] += buckets[i - 1]

    n_ans = len(answers)
    mul = int(n_ans * 0.6180339887)
    while math.gcd(mul, n_ans) != 1:
        mul += 1
    add = n_ans // 3

    lines = []
    lines.append("/* Generated by apps/wordle/tools/make_wordle.py from apps/wordle/tools/wordle/ -- do not edit.")
    lines.append(" *")
    lines.append(" * %d accepted words (ENABLE2K's five-letter words, public domain, less" % len(allw))
    lines.append(" * apps/wordle/tools/wordle/blocked.txt), %d of them answers (apps/wordle/tools/wordle/answers.txt)." % n_ans)
    lines.append(" * See apps/wordle/wordle.h for how they are packed and read. */")
    lines.append("#ifndef CARDOS_WORDLE_WORDS_H")
    lines.append("#define CARDOS_WORDLE_WORDS_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("#define WD_NWORDS    %d" % len(allw))
    lines.append("#define WD_NANSWERS  %d" % n_ans)
    lines.append("#define WD_DAILY_MUL %d   /* coprime with WD_NANSWERS */" % mul)
    lines.append("#define WD_DAILY_ADD %d" % add)
    lines.append("")
    lines.append("/* Where the words starting with each two letters begin in WD_TAIL;")
    lines.append(" * [26 * 26] is the end. */")
    lines.append("static const uint16_t WD_BUCKET[26 * 26 + 1] = {")
    for i in range(0, len(buckets), 12):
        lines.append("  " + ", ".join("%d" % b for b in buckets[i:i + 12]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("/* Letters three to five, five bits each, high first; bit 15: an answer. */")
    lines.append("static const uint16_t WD_TAIL[WD_NWORDS] = {")
    for i in range(0, len(tails), 12):
        lines.append("  " + ", ".join("0x%04x" % t for t in tails[i:i + 12]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%s: %d words, %d answers, %d bytes of constants"
          % (os.path.relpath(OUT, ROOT), len(allw), n_ans, 2 * (len(buckets) + len(tails))))


if __name__ == "__main__":
    sys.exit(main())
