FIRST, LAST = 32, 126


def columns(art):
    rows = list(art) + ["....."] * (8 - len(art))
    assert len(rows) == 8, len(rows)
    cols = []
    for c in range(5):
        bits = 0
        for r in range(8):
            assert len(rows[r]) == 5, rows[r]
            if rows[r][c] == "#":
                bits |= 1 << r
        cols.append(bits)
    cols.append(0)                      # the spacing column
    return cols


def render(cols):
    return ["".join("#" if (cols[c] >> r) & 1 else "." for c in range(6))
            for r in range(8)]


def main():
    table = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        if ch not in ART:
            raise SystemExit("no art for %r (0x%02X)" % (ch, code))
        table.append((ch, columns(ART[ch])))

    if "--show" in sys.argv:
        for ch, cols in table:
            print("%s:" % ch)
            for line in render(cols):
                print("  " + line)
        return

    lines = [
        "/* A 6x8 bitmap font, generated by tools/make_font.py -- do not edit.",
        " *",
        " * Column-major: byte n is column n from the left, bit 0 the top row.",
        " * Five columns of ink and one of spacing; row 7 carries descenders.",
        " *",
        " * Edit the pictures in the generator, not the hex. The table this",
        " * replaced had lost column 0 of every glyph -- H had a single stem --",
        " * and hex is where that kind of mistake hides.",
        " */",
        "#ifndef CARDOS_FONT6X8_H",
        "#define CARDOS_FONT6X8_H",
        "",
        "#include <stdint.h>",
        "",
        "#define FONT_W 6",
        "#define FONT_H 8",
        "#define FONT_FIRST %d" % FIRST,
        "#define FONT_LAST %d" % LAST,
        "",
        "static const uint8_t font6x8[%d][6] = {" % len(table),
    ]
    for ch, cols in table:
        label = {" ": "space", "\\": "backslash", "*": "asterisk"}.get(ch, ch)
        lines.append("  { %s },  /* %s */"
                     % (", ".join("0x%02X" % c for c in cols), label))
    lines += ["};", "", "#endif /* CARDOS_FONT6X8_H */"]

    with open("kernel/console/font6x8.h", "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote kernel/console/font6x8.h (%d glyphs)" % len(table))


if __name__ == "__main__":
    main()
