#!/usr/bin/env python3
"""Generate kernel/ui/icons_builtin.h -- 16x16 icons for the built-in apps.

The launcher draws every icon at 4x, so these are read as 64x64 pixel art and
every set bit is a visible 4x4 block. They are written here as pictures for the
same reason the font is: --show renders the generated table back out, so a
wrong row is visible rather than hiding in hex.

Format matches what a .capp supplies -- 16 rows of 2 bytes, bit 7 leftmost --
so the launcher has one drawing path for built-ins and loaded apps alike.
"""

